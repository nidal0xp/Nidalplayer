let currentLang = typeof localStorage !== 'undefined' ? (localStorage.getItem('nidalplayer-lang') || 'en') : 'en';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (translations[lang]) {
    currentLang = lang;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('nidalplayer-lang', lang);
    }
    applyTranslations();
  }
}

export function t(key) {
  return translations[currentLang]?.[key] || translations['en']?.[key] || key;
}

export function applyTranslations() {
  if (typeof document === 'undefined') return;
  const lang = currentLang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  // Apply to all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key && translations[lang]?.[key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Apply to placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && translations[lang]?.[key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Apply to titles / tooltips
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key && translations[lang]?.[key]) {
      el.title = translations[lang][key];
    }
  });

  // Sync all language selectors in DOM
  document.querySelectorAll('.lang-dropdown, #appLanguageSelect, #settingLangSelect, #bootLanguageSelect').forEach(select => {
    if (select && select.value !== lang) {
      select.value = lang;
    }
  });

  // Update active states on language chips
  document.querySelectorAll('.home-lang-btn, .lang-chip').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

// Automatically apply saved language on script load
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyTranslations());
  } else {
    applyTranslations();
  }
}

